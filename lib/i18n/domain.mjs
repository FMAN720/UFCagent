const nameLookup = new Map(
  Object.entries(fighterNames).map(([en, zh]) => [en.toLowerCase(), zh]),
);
export function displayName(name, locale = 'zh') {
  return locale === 'en'
    ? name
    : nameLookup.get(String(name).toLowerCase()) || name;
}
export function searchName(query) {
  const q = String(query).trim();
  return (
    Object.entries(fighterNames).find(
      ([, zh]) => zh === q || zh.replaceAll('·', '') === q.replaceAll('·', ''),
    )?.[0] || q
  );
}
export function displayDomain(text, locale) {
  if (locale === 'en') return divisions[text] || searchName(text);
  if (terms[text]) return terms[text];
  const name = displayName(text, locale);
  if (name !== text) return name;
  if (/^(UFC\b|Noche UFC\b|Road to UFC\b)/i.test(text)) {
    let result = text
      .replace(/UFC Fight Night/gi, 'UFC 格斗之夜')
      .replace(/Noche UFC/gi, 'UFC 墨西哥之夜')
      .replace(/Road to UFC/gi, 'UFC 精英之路')
      .replace(/\s+vs\.?\s+/gi, ' 对阵 ');
    const surnameLookup = new Map();
    for (const [en, zh] of Object.entries(fighterNames)) {
      const last = en.split(' ').at(-1);
      if (surnameLookup.has(last)) surnameLookup.set(last, null);
      else surnameLookup.set(last, zh.split('·').at(-1));
    }
    for (const [en, zh] of Object.entries(fighterNames).sort(
      (a, b) => b[0].length - a[0].length,
    ))
      result = result.replaceAll(en, zh);
    for (const [en, zh] of surnameLookup)
      if (zh)
        result = result.replace(
          new RegExp(
            '\\b' + en.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\b',
            'g',
          ),
          zh,
        );
    return result
      .replaceAll('Rosas Jr.', '罗萨斯')
      .replaceAll('Las Vegas', '拉斯维加斯');
  }
  if (text.includes(' · '))
    return text
      .split(' · ')
      .map((part) => terms[part] || part)
      .join(' · ');
  if (/^\d+(\.\d+)? lbs$/.test(text))
    return `${(parseFloat(text) * 0.45359237).toFixed(1)} 千克`;
  const h = text.match(/^(\d+)'\s*(\d+(?:\.\d+)?)"$/);
  if (h)
    return `${((Number(h[1]) * 12 + Number(h[2])) * 2.54).toFixed(1)} 厘米`;
  if (/^\d+(\.\d+)?"$/.test(text))
    return `${(parseFloat(text) * 2.54).toFixed(1)} 厘米`;
  return text;
}
